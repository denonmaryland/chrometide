const {chromium}=require(process.env.PW_PATH || 'playwright');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--ignore-gpu-blocklist','--enable-gpu','--use-angle=gl']});
  try {
    const page=await browser.newPage({viewport:{width:1280,height:900}});
    const errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
    const done=()=>page.waitForFunction(()=>window.__done===true,null,{timeout:120000});
    const pixels=()=>page.locator('#cv').evaluate(c=>c.toDataURL());
    await page.goto(process.argv[2]+'?lettering');
    await done();
    assert.equal(await page.locator('#titleText').inputValue(),'LOW TIDE');
    await page.locator('#cv').screenshot({path:'shots/chrome-title.png'});
    const original=await pixels();
    await page.locator('#titleText').fill('NÉON');
    await done();
    assert.notEqual(await pixels(),original);
    await page.locator('#titleLift').fill('2.5');
    await done();
    const changed=await pixels();
    await page.reload(); await done();
    assert.equal(await page.locator('#titleText').inputValue(),'NÉON');
    assert.equal(await pixels(),changed);
    await page.locator('#present').click();
    await page.locator('#turntable').click();
    await page.waitForTimeout(1700);
    await page.locator('#turntable').click(); await done();
    await page.locator('#cv').screenshot({path:'shots/chrome-title-orbit.png'});
    assert.notEqual(await pixels(),changed);
    await page.locator('#exitShow').click(); await done();
    assert.equal(await pixels(),changed);
    const download=page.waitForEvent('download');
    await page.locator('#save').click();
    assert.match((await download).suggestedFilename(),/\.png$/);
    await page.locator('#titleText').fill(''); await done();
    assert.notEqual(await pixels(),changed);
    assert.deepEqual(errors,[]);
    console.log('Demo, Unicode editing, height, link reload, orbit, exit, PNG and clearing passed.');
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1});
